#!/usr/bin/env node
// Generate the webfaCe Desk agent presets from apps/cli/config/agent-presets/desk-team.yml.
// Each teammate becomes a preset derived from dsh's `standard` composition with its own
// persona; every Desk preset gets one delegation tool per teammate (ask_<id>) so teammates
// can hand work to each other. Idempotent: run after editing desk-team.yml.
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const presetsDir = resolve(root, 'apps/cli/config/agent-presets')
const spec = yaml.load(readFileSync(resolve(presetsDir, 'desk-team.yml'), 'utf8'))
const standard = readFileSync(resolve(presetsDir, 'standard/agent.cordis.yml'), 'utf8')

const SHELL_TOOLS = ['bash', 'pwsh', 'str_replace_editor', 'write', 'edit', 'run_code', 'terminal_open', 'terminal_send', 'terminal_signal', 'terminal_close']
const TEAM_TOOLS = spec.teammates.map(t => `ask_${t.id.replace(/-/g, '_')}`)
const indent = (text, n) => text.trim().split('\n').map(l => ' '.repeat(n) + l).join('\n')
const yamlStr = (s) => JSON.stringify(s)

function askRows(self) {
  return spec.teammates.filter(t => t.id !== self.id).map(t => {
    const tool = `ask_${t.id.replace(/-/g, '_')}`
    // Children never delegate further (no ask_* → no loops) and business teammates keep no shell.
    const deny = [...TEAM_TOOLS, ...(t.shell ? [] : SHELL_TOOLS)]
    return [
      `    - id: tool-${tool}`,
      `      name: '@deepseek-ai/dsh-tool-subagent'`,
      `      config:`,
      `        provider: spawn`,
      `        toolName: ${tool}`,
      `        backgroundMode: continuable`,
      `        agentOptions:`,
      `          persona: >-`,
      indent(t.persona, 12),
      `          toolFilter:`,
      `            deny: [${deny.map(yamlStr).join(', ')}]`,
      '',
    ].join('\n')
  }).join('\n')
}

for (const t of spec.teammates) {
  let y = standard
  // persona
  y = y.replace(/(- id: persona\n  name: '@deepseek-ai\/dsh-persona'\n  config:\n    text: >-\n)(?:      .*\n)+/, `$1${indent(t.persona, 6)}\n`)
  if (!t.shell) {
    y = y.replace(/(- id: tool-bash\n  name: '@deepseek-ai\/dsh-tool-bash'\n  disabled: )!!js [^\n]+/, '$1true')
    y = y.replace(/(- id: tool-pwsh\n  name: '@deepseek-ai\/dsh-tool-pwsh'\n  disabled: )!!js [^\n]+/, '$1true')
  }
  // teammates' delegation tools, inside the delegation group beside `subagent`
  y = y.replace(/(    - id: tool-subagent-fork\n)/, `${askRows(t)}\n$1`)
  const header = `# GENERATED by scripts/gen-desk-presets.mjs from desk-team.yml — edit that file, not this one.\n`
  const dir = resolve(presetsDir, t.id); mkdirSync(dir, { recursive: true })
  writeFileSync(resolve(dir, 'agent.cordis.yml'), header + y)
  writeFileSync(resolve(dir, 'preset.yml'), yaml.dump({ name: t.name, description: t.description, order: t.order }, { lineWidth: 1000 }))
  // skills: copied per teammate from desk-skills/ so each preset's roster is explicit
  const skillsDir = resolve(dir, 'skills'); if (existsSync(skillsDir)) rmSync(skillsDir, { recursive: true })
  for (const name of t.skills ?? []) cpSync(resolve(presetsDir, 'desk-skills', name), resolve(skillsDir, name), { recursive: true })
  console.log(`preset ${t.id}: shell=${t.shell} asks=${spec.teammates.filter(x => x.id !== t.id).length} skills=${(t.skills ?? []).length}`)
}
